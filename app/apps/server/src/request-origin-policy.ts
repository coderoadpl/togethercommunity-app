export const isSafeMethod = (method: string): boolean => ['GET', 'HEAD', 'OPTIONS'].includes(method);

const matchesPath = (pattern: string, path: string): boolean => {
  const expected = pattern.split('/');
  const actual = path.split('/');
  return expected.length === actual.length && expected.every((part, index) =>
    part.startsWith(':') ? actual[index] !== '' : part === actual[index]);
};

export const requestOriginPolicy = (method: string, path: string): RequestOriginPolicy => {
  if (path.startsWith(BETTER_AUTH_API_PATH_PATTERN.slice(0, -1))) return 'auth';
  return REQUEST_ORIGIN_ROUTES.find((entry) => entry.method === method && matchesPath(entry.path, path))?.policy ?? 'session';
};

export const assertRequestOriginCoverage = (routes: readonly Route[]): void => {
  const missing = routes.filter((route) => route.method !== 'ALL' && !isSafeMethod(route.method))
    .filter((route) => !REQUEST_ORIGIN_ROUTES.some((entry) => entry.method === route.method && entry.path === route.path));
  if (missing.length > 0) {
    throw new Error(`Unsafe routes missing origin policy: ${missing.map((route) => `${route.method} ${route.path}`).join(', ')}`);
  }
};
