const hostOf = (url: string): string => {
  try {
    return new URL(url).hostname.toLowerCase().replace(/^www\./u, '');
  } catch {
    return '';
  }
};

const brandFor = (url: string) => {
  const host = hostOf(url);
  return (
    BRANDS.find((brand) =>
      brand.hosts.some((candidate) => host === candidate || host.endsWith(`.${candidate}`)),
    ) ?? null
  );
};

export const SocialLinksFooter = ({
  links,
  ariaLabel,
}: {
  links: readonly SocialLinkItem[];
  ariaLabel: string;
}) => (
  <SocialFooterBar component="nav" aria-label={ariaLabel} data-testid="tenant-social-links">
    {links.map((item) => {
      const brand = brandFor(item.url);
      return (
        <SocialFooterLink
          key={`${item.label}:${item.url}`}
          href={item.url}
          target="_blank"
          rel="noreferrer"
        >
          <SocialLinkIcon
            aria-hidden
            viewBox="0 0 24 24"
            data-testid={`social-icon-${brand?.key ?? 'generic'}`}
          >
            <path d={brand?.path ?? GENERIC_PATH} />
          </SocialLinkIcon>
          {item.label}
        </SocialFooterLink>
      );
    })}
  </SocialFooterBar>
);
